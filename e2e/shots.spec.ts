import { test, type Page } from "@playwright/test";
import { boot, caretAfter, expandLibrary } from "./helpers";
const dir = process.env.SHOTS!;
test.skip(!dir, "screenshots only on demand");
test.use({ deviceScaleFactor: Number(process.env.SCALE ?? 1) });
const only = (process.env.ONLY ?? "").split(",").filter(Boolean);
const shot = async (page: Page, name: string) => {
  if (only.length && !only.some((o) => name.includes(o))) return;
  await page.waitForTimeout(350);
  await page.screenshot({ path: `${dir}/${name}.png` });
};
async function mock(page: Page) {
  await page.route("http://localhost:1234/v1/chat/completions", async (r) => {
    const body = r.request().postDataJSON();
    const text = body.messages.map((m: any) => m.content).join("\n");
    const out = text.includes("NETFLIX") ? "SQ *JOE COFFEE COMPANY -> food.coffee\nNETFLIX.COM -> fun.streaming\nDELTA AIR 0062378712 -> travel.flights" : "Okay.";
    await r.fulfill({ status: 200, headers: { "access-control-allow-origin": "*", "content-type": "application/json" }, body: JSON.stringify({ choices: [{ message: { content: out } }] }) });
  });
}
